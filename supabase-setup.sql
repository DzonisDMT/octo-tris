-- OCTO-TRIS global leaderboard
-- Run this once in Supabase Dashboard > SQL Editor.
create table if not exists public.octotris_scores (
  id bigint generated by default as identity primary key,
  nickname text not null check (char_length(nickname) between 1 and 16),
  score integer not null check (score between 1 and 100000000),
  lines integer not null default 0 check (lines between 0 and 100000),
  level integer not null default 1 check (level between 1 and 1000),
  created_at timestamptz not null default now()
);
create index if not exists octotris_scores_score_created_idx
  on public.octotris_scores (score desc, created_at desc);
alter table public.octotris_scores enable row level security;
drop policy if exists "Public can read OCTO-TRIS scores" on public.octotris_scores;
create policy "Public can read OCTO-TRIS scores"
  on public.octotris_scores for select to anon using (true);
drop policy if exists "Public can submit OCTO-TRIS scores" on public.octotris_scores;
create policy "Public can submit OCTO-TRIS scores"
  on public.octotris_scores for insert to anon
  with check (
    char_length(nickname) between 1 and 16
    and score between 1 and 100000000
    and lines between 0 and 100000
    and level between 1 and 1000
  );
grant select, insert on public.octotris_scores to anon;
grant usage, select on sequence public.octotris_scores_id_seq to anon;
